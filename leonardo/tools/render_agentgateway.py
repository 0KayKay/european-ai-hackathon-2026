"""Render infrastructure/leonardo/agentgateway.yaml: the base config plus Leonardo and B300 routes.

agentgateway refuses to start when a key file it references is missing, so the Leonardo routes
cannot live in the base config, which every local stack uses. The opt-in Kustomize component
replaces the config with this rendered copy instead. Every served_model in serve/profiles/ and
b300/serve/models.json gets an OpenAI-compatible route to the leonardo-router Service, with the
router token as its key and the same optional request guardrails as the default route.
Challenge guardrails run in the backend.
Exact model names win over the "*" route.

    python3 tools/render_agentgateway.py          # write
    python3 tools/render_agentgateway.py --check  # fail if stale (check_repository.py runs this)
"""
import argparse
import json
from pathlib import Path
import sys

LEONARDO = Path(__file__).resolve().parents[1]
BASE = LEONARDO.parent / 'infrastructure/base/agentgateway.yaml'
OUTPUT = LEONARDO.parent / 'infrastructure/leonardo/agentgateway.yaml'
UPSTREAM = 'http://leonardo-router:8080/v1'
B300_UPSTREAM = 'http://b300-router:8080/v1'
TOKEN_FILE = '/var/run/leonardo-router/token'


def served_models():
    models = {}
    for path in (LEONARDO / 'serve/profiles').glob('*.json'):
        model = json.loads(path.read_text())['served_model']
        models[model] = (model, UPSTREAM)
    # GLM's validated B300 server keeps its legacy served name; the gateway identifies its location.
    models.update((model['served_model'].replace('-leonardo', '-b300'), (model['served_model'], B300_UPSTREAM)) for model in
                  json.loads((LEONARDO.parent / 'b300/serve/models.json').read_text()).values())
    return models


def guardrails(lines):
    """The default model's guardrails block, at its original indentation."""
    if '      guardrails:' not in lines:
        return []
    start = lines.index('      guardrails:')
    end = start + 1
    while end < len(lines) and (not lines[end].strip() or lines[end].startswith('       ')):
        end += 1
    return lines[start:end]


def render():
    lines = BASE.read_text().splitlines()
    if lines.count('  models:') != 1:
        raise SystemExit('Expected exactly one "  models:" line in ' + str(BASE))
    # Profiles can share a served name (the same model on another runtime); one route each.
    entries = []
    for model, (upstream, base_url) in sorted(served_models().items()):
        entries += ['    - name: ' + model, '      provider: openAI', '      params:', '        baseUrl: ' + base_url,
                    '      auth:', '        key:', '          file: ' + TOKEN_FILE] + guardrails(lines)
        if upstream != model:
            entries += ['      transformation:', '        model: ' + "'" + json.dumps(upstream) + "'"]
    position = lines.index('  models:') + 1
    header = ['# Generated by leonardo/tools/render_agentgateway.py from ../base/agentgateway.yaml. Do not edit.']
    first = 1 if lines[0].startswith('# yaml-language-server') else 0
    out = lines[:first] + header + lines[first:position] + entries + lines[position:]
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            sys.exit('FAIL: {} is stale: run python3 tools/render_agentgateway.py'.format(OUTPUT))
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    print('Wrote {} with routes for: {}'.format(OUTPUT, ', '.join(sorted(served_models()))))


if __name__ == '__main__':
    main()
